"""Automated markdown operational report generator."""
import datetime
from typing import Dict, Any

def generate_markdown_shift_report(data: Dict[str, Any]) -> str:
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    report = [
        f"# Hazira Operational Shift Report - {now_str}",
        "",
        "## Summary Metrics",
        f"- **Total Production**: {data.get('total_units', 0):,} units",
        f"- **Overall OEE**: {data.get('avg_oee', 0.0) * 100:.1f}%",
        f"- **Total Downtime**: {data.get('total_downtime_hours', 0.0):.1f} hours",
        f"- **Energy Consumed**: {data.get('total_energy_kwh', 0.0):,.0f} kWh",
        "",
        "## Critical Action Items",
        f"- High Risk Machines: {data.get('critical_machines_count', 0)}",
        "- Scheduled Maintenance Backlog: Up to date",
        "",
        "---",
        "*Report auto-generated by L&T Hazira Analytics Engine*"
    ]
    return "\n".join(report)
